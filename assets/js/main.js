function findOverflowingElements() {
    const clientWidth = document.documentElement.clientWidth;
    const all = document.querySelectorAll('*');
    const offenders = [];

    all.forEach(el => {
        const rect = el.getBoundingClientRect();
        const style = getComputedStyle(el);

        const marginLeft = parseFloat(style.marginLeft) || 0;
        const marginRight = parseFloat(style.marginRight) || 0;

        // effective right edge including margin
        const effectiveRight = rect.right + marginRight;
        const effectiveLeft = rect.left - marginLeft;
        const effectiveWidth = effectiveRight - effectiveLeft;

        if (effectiveRight > clientWidth || effectiveLeft < 0) {
            const tag = el.tagName.toLowerCase();
            const classes = el.className && typeof el.className === 'string'
                ? '.' + el.className.trim().split(/\s+/).join('.')
                : '';

            offenders.push({
                el,
                label: `${tag}${classes}`,
                boxWidth: Math.round(rect.width),
                effectiveWidth: Math.round(effectiveWidth),
                effectiveRight: Math.round(effectiveRight),
                marginLeft,
                marginRight,
                paddingLeft: parseFloat(style.paddingLeft) || 0,
                paddingRight: parseFloat(style.paddingRight) || 0,
                borderLeft: parseFloat(style.borderLeftWidth) || 0,
                borderRight: parseFloat(style.borderRightWidth) || 0,
                boxSizing: style.boxSizing
            });
        }
    });

    console.log(`Client width: ${clientWidth}px`);
    console.table(offenders.map(o => ({
        element: o.label,
        boxWidth: o.boxWidth,
        effectiveWidth: o.effectiveWidth,
        effectiveRight: o.effectiveRight,
        marginL: o.marginLeft,
        marginR: o.marginRight,
        padL: o.paddingLeft,
        padR: o.paddingRight,
        borderL: o.borderLeft,
        borderR: o.borderRight,
        boxSizing: o.boxSizing
    })));
    return offenders.map(o => o.el);
}

